    /**
     * Arabic names Cathedis's sheet gives that CityService does not know.
     *
     * @var array<string, string>
     */
    private const ARABIC_NAMES = [
        'Goulmima' => 'كلميمة',
        "Kelâat M'Gouna" => 'قلعة امڭونة',
        'Laayoun Charkia' => 'العيون الشرقية',
    ];

    public function run(): void
    {
        $names = app(CityService::class);

        $cathedis = DeliveryService::firstOrCreate(
            ['slug' => self::SLUG],
            [
                'name' => 'Cathedis',
                'description' => 'Livraison partout au Maroc via Cathedis.',
                'pricing' => DeliveryService::PRICING_DESTINATION,
                'is_active' => true,
                'sort_order' => 1,
            ],
        );

        $registry = City::all()->keyBy(fn (City $city) => $this->matchKey($city->name));

        foreach (self::CITIES as $name => $fee) {
            $city = $registry->get($this->matchKey($name))
                ?? City::create([
                    'name' => $name,
                    'name_translations' => $names->translationsFor($name, ['ar' => self::ARABIC_NAMES[$name] ?? null]),
                ]);

            DeliveryRate::firstOrCreate(
                [
                    'delivery_service_id' => $cathedis->id,
                    'country_code' => 'MA',
                    'city_id' => $city->id,
                ],
                ['country_name' => 'Maroc', 'fee' => $fee],
            );
        }
    }

    /** "Fès" and "fes", "Béni-Mellal" and "Beni Mellal" are the same city. */
    private function matchKey(string $name): string
    {
        return (string) preg_replace('/[^a-z]/', '', Str::lower(Str::ascii($name)));
    }
